// ── Context ──

function getBrowserLanguage(): string {
  if (typeof window === 'undefined') return 'en'
  try {
    const saved = localStorage.getItem('kalma-language')
    if (saved && translations[saved]) return saved
    const lang = (navigator.language || 'en').split('-')[0].toLowerCase()
    return translations[lang] ? lang : 'en'
  } catch {
    return 'en'
  }
}

interface TranslationContextType {
  t: (key: string) => string
  tpl: (key: string, vars: Record<string, string | number>) => string
  language: string
  changeLanguage: (lang: string) => void
  availableLanguages: string[]
}

const defaultT = (key: string): string => translations['en']?.[key] || key

function formatTemplate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ''))
}

const defaultTpl = (key: string, vars: Record<string, string | number>) =>
  formatTemplate(defaultT(key), vars)

const TranslationContext = createContext<TranslationContextType>({
  t: defaultT,
  tpl: defaultTpl,
  language: 'en',
  changeLanguage: () => {},
  availableLanguages: Object.keys(translations),
})

export function TranslationProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<string>('en')

  useEffect(() => {
    setLanguage(getBrowserLanguage())
  }, [])

  const t = (key: string): string => {
    return translations[language]?.[key] || translations['en']?.[key] || key
  }

  const tpl = (key: string, vars: Record<string, string | number>): string => {
    return formatTemplate(t(key), vars)
  }

  const changeLanguage = (lang: string) => {
    if (translations[lang]) {
      setLanguage(lang)
      try { localStorage.setItem('kalma-language', lang) } catch {}
    }
  }

  return (
    <TranslationContext.Provider value={{
      t, tpl, language, changeLanguage,
      availableLanguages: Object.keys(translations),
    }}>
      {children}
    </TranslationContext.Provider>
  )
}

export function useTranslation() {
  return useContext(TranslationContext)
}
